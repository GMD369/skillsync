import mongoose from "mongoose";

// One learning task inside a roadmap week. Each task gets its own _id so it can be
// updated directly (PATCH /api/career/roadmap/tasks/:taskId).
const taskSchema = new mongoose.Schema({
  title: { type: String, required: true, trim: true },
  done: { type: Boolean, default: false },
  doneAt: { type: Date, default: null },
});

const weekSchema = new mongoose.Schema(
  {
    week: { type: Number, required: true, min: 1 },
    skill: { type: String, required: true, trim: true },
    level: { type: String, enum: ["basic", "intermediate", "advanced"], default: "basic" },
    tasks: [taskSchema],
  },
  { _id: false }
);

// A student's week-by-week learning plan for the missing skills of their target role.
// Collection: roadmaps. Relationships: many-to-one with users (one roadmap per student,
// enforced by the unique index) and many-to-one with careerroles.
const roadmapSchema = new mongoose.Schema(
  {
    user: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true, unique: true },
    role: { type: mongoose.Schema.Types.ObjectId, ref: "CareerRole", required: true },
    // "rules" = generated from task templates (now); "ai" = generated by the LLM (module M5).
    source: { type: String, enum: ["rules", "ai"], default: "rules" },
    weeks: [weekSchema],
  },
  { timestamps: true }
);

// Progress numbers used by the roadmap page and the dashboard.
roadmapSchema.methods.progress = function () {
  const tasks = this.weeks.flatMap((w) => w.tasks);
  const done = tasks.filter((t) => t.done).length;
  return { totalTasks: tasks.length, doneTasks: done, percentage: tasks.length ? Math.round((done / tasks.length) * 100) : 0 };
};

roadmapSchema.set("toJSON", {
  transform: (doc, ret) => {
    delete ret.__v;
    return ret;
  },
});

export default mongoose.model("Roadmap", roadmapSchema);
